import i18n from "i18next";
import { initReactI18next } from "react-i18next";

export const APP_LANGUAGES = ["zh-CN", "en"] as const;
export type AppLanguage = (typeof APP_LANGUAGES)[number];

const DEFAULT_LANGUAGE: AppLanguage = "zh-CN";
const LANGUAGE_STORAGE_KEY = "leiblog-language";

export const normalizeLanguage = (language?: string | null): AppLanguage => {
  if (!language) {
    return DEFAULT_LANGUAGE;
  }

  return language.toLowerCase().startsWith("en") ? "en" : "zh-CN";
};

const getInitialLanguage = (): AppLanguage => {
  if (typeof window === "undefined") {
    return DEFAULT_LANGUAGE;
  }

  return normalizeLanguage(
    window.localStorage.getItem(LANGUAGE_STORAGE_KEY) ?? window.navigator.language,
  );
};

export const changeAppLanguage = (language: AppLanguage) => {
  if (typeof window !== "undefined") {
    window.localStorage.setItem(LANGUAGE_STORAGE_KEY, language);
  }

  void i18n.changeLanguage(language);
};

